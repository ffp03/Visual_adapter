// Real isolated Chromium, with Chrome messaging doubled. No site/provider calls.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'workspace/task023/preservation-v2/native');
fs.mkdirSync(output, { recursive: true });
const profile = fs.mkdtempSync(path.join(output, 'isolated-profile-'));
const script = name => fs.readFileSync(path.join(root, 'extension', name), 'utf8');
const html = '<!doctype html><base href="https://example.test/base/"><h1 id="title">Heading</h1><nav><div class=reading>Navigation duplicate</div></nav><main class=reading><p>Complete <a href="next">reading link</a> and <a href="#note">note</a></p><pre><code>if (x) {\n  return y;\n}</code></pre><table><tr><td>Cell</td></tr></table><ul><li>Entry</li></ul><p id="note">Note body</p></main><section role="comment"><p>Sibling discussion</p></section><footer><div class=reading>Footer duplicate</div></footer>';
const nativeTest = `
const observed = [];
let nativeRules = [];
const listeners = [];
chrome.runtime = { sendMessage: async () => ({ rules: nativeRules }), onMessage: { addListener: fn => listeners.push(fn) } };
const initialRule = { main: '.reading', name: 'retained candidate', exclude: ['pre'] };
const compiled = PreservationCore.compile(document, initialRule);
nativeRules = [compiled];
${script('content.js')}
const extract = () => new Promise(resolve => listeners[0]({ action: 'EXTRACT_CONTEXT' }, {}, resolve));
(async () => {
  observed.push(await extract());
  nativeRules = [{ ...initialRule, exclude: [] }]; observed.push(await extract());
  nativeRules = [{ main: 'body', exclude: [], name: 'legacy complete' }]; observed.push(await extract());
  nativeRules = [compiled]; const article = document.createElement('article'); article.innerHTML = '<p>New scaffold</p>'; document.body.appendChild(article); observed.push(await extract());
  document.body.innerHTML = ''; const result = document.createElement('pre'); result.id = 'native-result'; result.textContent = JSON.stringify(observed); document.body.appendChild(result);
})().catch(error => { document.body.textContent = 'FAILED:' + error.stack; });`;
const file = path.join(output, 'test.html');
fs.writeFileSync(file, html + '<script>' + script('procedure-core.js') + '</script><script>' + nativeTest + '</script>');
const chrome = process.env.PRESERVATION_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const result = spawnSync(chrome, ['--headless=new', '--disable-gpu', '--disable-background-networking', '--no-first-run', '--no-default-browser-check', '--host-resolver-rules=MAP * ~NOTFOUND', '--blink-settings=imagesEnabled=false', '--user-data-dir=' + profile, '--dump-dom', 'file:///' + file.replace(/\\/g, '/')], { encoding: 'utf8', timeout: 90000, maxBuffer: 8 * 1024 * 1024, windowsHide: true });
assert.equal(result.error, undefined, result.error?.message);
assert.equal(result.status, 0, result.stderr);
fs.writeFileSync(path.join(output, 'dump.html'), result.stdout);
const dom = new JSDOM(result.stdout);
const rows = JSON.parse(dom.window.document.getElementById('native-result')?.textContent || 'null');
assert(rows, result.stdout.slice(-2000));
assert.equal(rows[0].delivery, 'supplemented-procedure');
assert.equal(rows[0].supplementation, true);
assert.equal(rows[0].usedRule, true);
assert.equal(rows[0].pureModelSelection, false);
assert.equal(rows[0].runtimeSupplementation, false);
assert.equal(rows[0].ruleApplied, true);
assert.equal(rows[0].procedureDelivered, true);
assert.equal(rows[0].noFallback, true);
assert.equal(rows[0].coverage.accepted, true);
assert(rows[0].html.includes('<table>') && rows[0].html.includes('<ul>'));
assert(rows[0].html.includes('https://example.test/base/next'));
assert.equal(rows[1].usedRule, false);
assert.equal(rows[1].delivery, 'fallback');
assert.equal(rows[2].delivery, 'legacy-rule');
assert.equal(rows[2].usedRule, true);
assert.equal(rows[3].usedRule, false);
assert.equal(rows[3].ruleRejectionDetail, 'structural-scope-mismatch');
fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ mode: 'real-isolated-Chromium-with-messaging-double', results: rows }, null, 2));
dom.window.close();
console.log('Real isolated Chromium: supplemented procedure, rejected legacy fallback, complete legacy delivery and structural mismatch passed.');
