assert.throws(() => core.compile(duplicateServer.window.document, { main: '.reading', exclude: [], name: 'Ambiguous candidate' }), /exactly-once/);
outsideDuplicate.window.close(); duplicateServer.window.close();

const bodyClass = make('<body class=reading><main><p>Reading text</p></main></body>');
const bodyClassContext = core.validationContext(bodyClass.window.document);
assert(bodyClassContext.validationHTML.startsWith('<body class="reading">'));
const bodyClassServer = make(bodyClassContext.validationHTML);
const bodyClassProcedure = core.compile(bodyClassServer.window.document, { main: '.reading', exclude: [], name: 'Body region' });
