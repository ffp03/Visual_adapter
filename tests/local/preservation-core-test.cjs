const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const core = require('../../extension/procedure-core');
const make = html => new JSDOM(html, { url: 'https://example.test/section/page' });
const source = '<base href="https://example.test/base/"><h1 id="title">A title</h1><main><article><p>Complete prose <a href="next">reading destination</a> and <a href="#note">note</a>.</p><pre><code>const result = 1;</code></pre><table><tbody><tr><td>Cell</td></tr></tbody></table><ul><li>List entry</li></ul><figure><img src="photo.png" alt="A photo"><figcaption>Photo caption</figcaption></figure></article><section role="comment"><p>A sibling discussion.</p></section><p id="note">The footnote</p></main><nav>navigation</nav>';
const dom = make(source), doc = dom.window.document;
const model = { main: 'article', exclude: ['pre', 'table', 'ul', 'figure', '[role="comment"]', 'nav'], name: 'retained model candidate' };
const procedure = core.compile(doc, model);
const output = core.apply(doc, procedure);
assert.equal(output.accepted, true);
assert.equal(procedure.schemaVersion, 2);
assert(procedure.adjustments.some(a => a.kind === 'dropped-unsafe-exclusion'));
assert.equal(procedure.exclude.includes('pre'), false);
assert(output.html.includes('<table>'));
assert(output.html.includes('<ul>'));
assert(output.html.includes('https://example.test/base/next'));
assert(output.html.includes('https://example.test/base/photo.png'));
assert(output.html.includes('href="#note"'));
assert(output.html.includes('id="note"'));
assert(output.html.includes('A sibling discussion.'));
assert(output.html.includes('A title'));
assert.equal(core.applyLegacy(doc, { ...model, exclude: [] }).accepted, false);
assert.equal(core.assess(doc, '<h1>A title</h1><p>Complete prose</p>').accepted, false);
for (const a of procedure.regions) for (const b of procedure.regions) if (a !== b)
    assert.equal(doc.querySelector(a.selector).contains(doc.querySelector(b.selector)), false);
const changed = make(source.replace('<article>', '<article><p>New structural block</p><ul><li>Another list</li></ul><table><tr><td>Another table</td></tr></table>'));
assert.equal(core.apply(changed.window.document, procedure).accepted, true);
const incompatible = make('<main><p>Different scaffold</p></main>');
assert.equal(core.apply(incompatible.window.document, procedure).reason, 'region-must-match-exactly-once');
incompatible.window.close();
const optionalLandmark = make('<main><p>First content</p></main>');
const optionalProcedure = core.compile(optionalLandmark.window.document, { main: 'main', exclude: [], name: 'Optional inner landmark' });
const optionalSecond = make('<main><p>Second content</p><article><p>Additional reading block</p></article></main>');
assert.equal(core.apply(optionalSecond.window.document, optionalProcedure).accepted, true);
optionalLandmark.window.close(); optionalSecond.window.close();
const codeOnly = make('<main><pre><code>if (a) {\n  return b;\n}</code></pre></main>');
assert.equal(core.assess(codeOnly.window.document, '<main><pre><code>if (a) { return b; }</code></pre></main>').accepted, false);
codeOnly.window.close();
const unsafe = make('<main><p onclick="alert(1)"><a href="javascript:alert(1)">Read</a></p><script>alert(1)</script></main>');
const safe = core.apply(unsafe.window.document, core.compile(unsafe.window.document, { main: 'main', exclude: [], name: 'safe' }));
assert.equal(safe.accepted, true);
assert(!/onclick|javascript:|<script/.test(safe.html));
const rowSelection = make('<table id=parent><tr id=row><td>Complete row</td></tr></table>');
const promoted = core.compile(rowSelection.window.document, { main: '#row', exclude: [], name: 'Legacy row' });
assert.equal(promoted.supplementation, true);
assert.equal(promoted.modelSelectionSuperseded, true);
rowSelection.window.close();
const unmarked = make('<div><span>First readable fragment</span><small>Author identity</small></div><section><span>Second independent reading fragment</span></section>');
const unmarkedFallback = core.fallback(unmarked.window.document);
assert(unmarkedFallback.html.includes('First readable fragment') && unmarkedFallback.html.includes('Author identity') && unmarkedFallback.html.includes('Second independent reading fragment'));
assert.equal(unmarkedFallback.coverage.scopeIndeterminate, true);
assert.equal(core.applyLegacy(unmarked.window.document, { main: 'div', exclude: [], name: 'too narrow' }).accepted, false);
unmarked.window.close();
const activeSVG = make('<main><p>Reading text</p><svg><a id=graphic href="https://example.test/"><text>Graphic label</text></a><animate href="#graphic" attributeName="href" values="javascript:alert(1)"></animate><set href="#graphic" attributeName="onclick" to="alert(1)"></set></svg></main>');
const staticSVG = core.fallback(activeSVG.window.document).html;
assert(!/<animate|<set|javascript:|alert\(1\)/.test(staticSVG));
assert(staticSVG.includes('Graphic label'));
activeSVG.window.close();
const noiseDuplicate = make('<nav><div class=reading><p>Navigation only</p></div></nav><div class=reading><span>Actual readable section</span></div><footer><div class=reading>Footer only</div></footer>');
const eligibleProcedure = core.compile(noiseDuplicate.window.document, { main: '.reading', exclude: [], name: 'Eligible region' });
assert.equal(core.apply(noiseDuplicate.window.document, eligibleProcedure).accepted, true);
const twoReading = make('<div class=reading><p>One reading block</p></div><div class=reading><p>Second reading block</p></div>');
assert.throws(() => core.compile(twoReading.window.document, { main: '.reading', exclude: [], name: 'Ambiguous' }));
noiseDuplicate.window.close(); twoReading.window.close();
const externalNote = make('<div><main><p>Reading <a href="#external-note">note</a></p></main></div><aside><table><tr><td id=external-note>External note body</td></tr></table></aside>');
const externalFallback = core.fallback(externalNote.window.document);
assert.equal(externalFallback.coverage.accepted, true);
assert(externalFallback.html.includes('<table>') && externalFallback.html.includes('id="external-note"'));
assert.equal(core.apply(externalNote.window.document, core.compile(externalNote.window.document, { main: 'main', exclude: [], name: 'External fragment' })).accepted, true);
externalNote.window.close();
const bodyFragment = make('<body id=top><main><p>Reading <a href="#top">back to top</a></p></main></body>');
assert.equal(core.fallback(bodyFragment.window.document).coverage.accepted, true);
assert.equal(core.apply(bodyFragment.window.document, core.compile(bodyFragment.window.document, { main: 'main', exclude: [], name: 'Document fragment' })).accepted, true);
bodyFragment.window.close();
const bareText = make('<body>Unwrapped body prose<p>Separate paragraph</p></body>');
assert.equal(core.fallback(bareText.window.document).coverage.accepted, true); bareText.window.close();
const ambiguous = make('<div>Unmarked content only</div>');
assert(core.inspect(ambiguous.window.document).limits.includes('unmarked-body-content-indeterminate'));
const repeated = make('<main><div>Repeated direct prose</div><div>Repeated direct prose</div></main>');
assert.equal(core.assess(repeated.window.document, '<main><div>Repeated direct prose</div></main>').accepted, false);
repeated.window.close();
assert.equal(procedure.supplementation, true);
assert.equal(procedure.modelCandidate.main, model.main);
assert.equal(procedure.regions.find(region => region.role === 'model-reading-region').selector, 'article');
const privateControls = make('<main><p>Reading prose</p><input value=secretInput><textarea>secretTextarea</textarea></main>');
const privateContext = core.validationContext(privateControls.window.document);
assert.equal(privateContext.validationComplete, true);
assert(!privateContext.validationHTML.includes('secretInput') && !privateContext.validationHTML.includes('secretTextarea'));
assert.equal(core.fallback(privateControls.window.document).coverage.accepted, true);
privateControls.window.close();
const controls = make('<main><p>Readable thread</p><form><textarea></textarea><button>Submit</button></form></main>');
const reading = core.compile(controls.window.document, { main: 'main', exclude: [], name: 'Reading' });
const readingResult = core.apply(controls.window.document, reading);
assert.equal(readingResult.accepted, true);
assert.equal(readingResult.coverage.applicationFunctionalityVerified, false);
assert.equal(readingResult.coverage.unsupportedInteraction.length, 1);
controls.window.close();
dom.window.close(); changed.window.close(); unsafe.window.close(); ambiguous.window.close();
console.log('Preservation core: roles, expansion, exclusions, URL/base/fragments, structure and sanitization passed.');

const standaloneCode = make('<main><code><span>return</span><span class=space> </span><span>value</span></code></main>');
const codeRule = { main: 'main', exclude: ['.space'], name: 'Atomic code' };
assert.equal(core.applyLegacy(standaloneCode.window.document, codeRule).accepted, false);
const atomicProcedure = core.compile(standaloneCode.window.document, codeRule);
assert.equal(atomicProcedure.exclude.length, 0);
assert(core.apply(standaloneCode.window.document, atomicProcedure).html.includes('> </span>'));
standaloneCode.window.close();

const relocatedSource = make('<body><div>' + 'Unwrapped outside reading boundary. '.repeat(4000) + '</div><section><div><h1>Reading title</h1><main><p>Complete reading content</p></main></div></section></body>');
const oversizedContext = core.validationContext(relocatedSource.window.document);
assert.equal(oversizedContext.validationComplete, false);
assert.equal(oversizedContext.validationHTML, undefined);
assert.equal(oversizedContext.validationLimitation, 'complete-sanitized-body-exceeds-100k');
assert(core.fallback(relocatedSource.window.document).html.includes('Complete reading content'));
const completeSmallSource = make('<body><div>Outside reading boundary</div><section><div><h1>Reading title</h1><main><p>Complete reading content</p></main></div></section></body>');
const relocatedContext = core.validationContext(completeSmallSource.window.document);
assert.equal(relocatedContext.validationComplete, true);
const relocatedServer = make(relocatedContext.validationHTML);
const stableProcedure = core.compile(relocatedServer.window.document, { main: 'main', exclude: [], name: 'Stable shared ancestor' });
assert(stableProcedure.regions.every(region => !region.fragileSelector && !region.selector.includes('nth-of-type')));
assert.equal(core.apply(completeSmallSource.window.document, stableProcedure).accepted, true);
assert(stableProcedure.adjustments.some(adjustment => adjustment.kind === 'stable-common-ancestor-expansion'));
const wrapperInsertion = make('<body><div>Unrelated prefix</div><section><aside>New optional wrapper</aside><div><h1>Different reading title</h1><main><p>Different complete reading text</p></main></div></section></body>');
assert.equal(core.apply(wrapperInsertion.window.document, stableProcedure).accepted, true);
relocatedSource.window.close(); completeSmallSource.window.close(); relocatedServer.window.close(); wrapperInsertion.window.close();

const outsideDuplicate = make('<body><div class=reading>Outside text</div><main><div class=reading><p>Required reading prose</p></div></main></body>');
const duplicateContext = core.validationContext(outsideDuplicate.window.document);
